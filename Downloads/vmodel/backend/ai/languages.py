def resolve_language(query: str) -> tuple[str, str] | None:
    """Resolve a user query to (code, name).

    Accepts exact codes (fr, zh-CN), exact names (French), unique
    substrings ("hind" -> Hindi), and common aliases (farsi -> fa).
    Ambiguous queries prefer the bare base-language code (chinese -> zh).
    """
    q = (query or "").strip().lower()
    if not q:
        return None
    if q in _ALIASES:
        code = _ALIASES[q]
        return code, LANGUAGES[code]
    if q in LANGUAGES:
        return q, LANGUAGES[q]
    for code, name in LANGUAGES.items():
        if name.lower() == q:
            return code, name
    matches = [
        (code, name) for code, name in LANGUAGES.items()
        if q in name.lower() or q in code.lower()
    ]
    if not matches:
        return None
    if len(matches) == 1:
        return matches[0]
    # ambiguous: prefer bare base codes (no region suffix), then shortest
    bare = [m for m in matches if "-" not in m[0]]
    pool = bare or matches
    pool.sort(key=lambda m: len(m[0]))
    return pool[0]
